#!/usr/bin/env python3
"""Two equivalent forms of the D = infinity inner problem (math paper Prop. 5(i), eq. (8)), checked symbolically.

Eq. (8):  Y_t = c W,  W_t = c (Y_s + Y^3/4),  c_s = c Y^2/4.

(A) Gauge-fixed form. With the proper length u = int c dt along s = const (u_t = c) and the drift V = u_s at fixed t,
    and Yh(s, u) = Y(s, t):
        Yh_s + (V Yh)_u = Yh_uu,        V_u = Yh^2/4,
    a drift-diffusion (Fokker-Planck) equation whose drift is generated by the field. The t-reparametrisation gauge
    drops out; what is left is u -> u + h(s), V -> V + h'(s).
    Check: with Y(s, t) = Yh(s, u(s, t)), c = u_t, the residuals of (8) are combinations of those of (A):
        W_t - c (Y_s + Y^3/4) = -c * A1 + c * Yh * A2,      c_s - c Y^2/4 = c * A2,
    A1 = Yh_s + (V Yh)_u - Yh_uu, A2 = V_u - Yh^2/4, V(s, u(s, t)) = u_s.

(L) List's flow on a line. In Rozali and Way's potential form (the proof of Prop. 5(i): phi_s = c^-1 d_t(c^-1 phi_t),
    c_s = phi_t^2/c, Y = 2 phi_t/c), with the metric g = c^2 dt^2 on the t-line,
        d_s g = 2 dphi (x) dphi,        d_s phi = Laplacian_g phi,
    which is the Ricci flow coupled to the harmonic map flow, d_s g = -2 Rc + 2 alpha dphi (x) dphi, d_s phi = tau_g phi
    (R. Muller, Ann. Sci. ENS 45 (2012) 101, arXiv:0912.2907), with alpha = 1 and target R, on a one-dimensional domain
    where Rc = 0; with phi = sqrt(2) psi it is List's flow (B. List, Comm. Anal. Geom. 16 (2008) 1007), alpha = 2.
    Check: g_tt = c^2, Laplacian_g phi = c^-1 d_t(c^-1 phi_t); d_s(c^2) = 2 c c_s = 2 phi_t^2.

    python3 heat_forms.py [--mutate=quarter]     the mutation uses Y^3/2 in (8) and must make the check fail

Exit status 0 only if both identities hold (and, with the mutation, only if the check fails as it must).
"""
import sys

import sympy as sp


def main(argv):
    mut = "--mutate=quarter" in argv
    cub = sp.Rational(1, 2) if mut else sp.Rational(1, 4)
    s, t, U = sp.symbols("s t U")
    u = sp.Function("u")(s, t)
    # Yh is a general cubic in (s, U) with symbolic coefficients: its value and first and second partial derivatives at
    # a point are independent, so an identity in the 2-jet of Yh that holds for it holds for every Yh
    acoef = {(i, j): sp.Symbol(f"a{i}{j}") for i in range(4) for j in range(4) if i + j <= 3}

    def Yh(S, X):
        return sum(cf * S ** i * X ** j for (i, j), cf in acoef.items())

    V = sp.Function("V")
    # Y(s, t) = Yh(s, u(s, t)); c = u_t
    Y = Yh(s, u)
    c = sp.diff(u, t)
    W = sp.diff(Y, t) / c
    E1 = sp.diff(W, t) - c * (sp.diff(Y, s) + cub * Y ** 3)
    E2 = sp.diff(c, s) - c * Y ** 2 / 4
    # (A) residuals at u = u(s, t); V is defined by V(s, u(s, t)) = u_s, hence V_u = u_st/u_t, V = u_s
    YhU = Yh(s, U)
    A1 = sp.diff(YhU, s) + sp.diff(V(s, U) * YhU, U) - sp.diff(YhU, U, 2)
    A2 = sp.diff(V(s, U), U) - YhU ** 2 / 4
    rule = {sp.Derivative(V(s, U), U): sp.diff(u, s, t) / sp.diff(u, t), V(s, U): sp.diff(u, s)}
    A1u = A1.subs(rule).subs(U, u)
    A2u = A2.subs(rule).subs(U, u)
    id1 = sp.simplify(sp.expand((E1 - (-c * A1u + c * Y * A2u)).doit()))
    id2 = sp.simplify(sp.expand((E2 - c * A2u).doit()))
    short = lambda e: str(e) if len(str(e)) < 80 else f"nonzero ({len(sp.Add.make_args(sp.expand(e)))} terms)"
    print(f"(A): (8a) - (-c A1 + c Y A2) = {short(id1)};   (8b) - c A2 = {short(id2)}")
    # (L): Rozali-Way potential form <-> List's flow on a line
    phi = sp.Function("phi")(s, t)
    cc = sp.Function("c")(s, t)
    g = cc ** 2
    lap = sp.diff(sp.diff(phi, t) / sp.sqrt(g), t) / sp.sqrt(g)            # 1-d Laplace-Beltrami, g = c^2 dt^2
    rw_field = sp.diff(phi, s) - sp.diff(sp.diff(phi, t) / cc, t) / cc
    rw_lapse = sp.diff(cc, s) - sp.diff(phi, t) ** 2 / cc
    list_field = sp.diff(phi, s) - lap
    list_metric = sp.diff(g, s) - 2 * sp.diff(phi, t) ** 2
    pos = {cc: sp.Symbol("C", positive=True)}
    idL1 = sp.simplify((list_field - rw_field).subs(cc, sp.Abs(cc)).rewrite(sp.Abs)) if False else \
        sp.simplify(sp.powdenest(sp.expand(list_field - rw_field), force=True))
    idL2 = sp.simplify(list_metric - 2 * cc * rw_lapse)
    print(f"(L): List field - RW field = {idL1};   List metric - 2 c * RW lapse = {idL2}")
    # and the RW potential form gives (8): Y = 2 phi_t/c, W = Y_t/c satisfy (8b) and (8a) given the RW equations
    Yp = 2 * sp.diff(phi, t) / cc
    Wp = sp.diff(Yp, t) / cc
    e8a = sp.diff(Wp, t) - cc * (sp.diff(Yp, s) + cub * Yp ** 3)
    e8b = sp.diff(cc, s) - cc * Yp ** 2 / 4
    sol = {sp.Derivative(phi, s): sp.diff(sp.diff(phi, t) / cc, t) / cc, sp.Derivative(cc, s): sp.diff(phi, t) ** 2 / cc}

    def reduce(e):
        # replace phi_s, c_s and their t-derivatives using the RW equations
        for _ in range(3):
            e = e.subs({sp.Derivative(phi, s, t): sp.diff(sol[sp.Derivative(phi, s)], t),
                        sp.Derivative(phi, t, s): sp.diff(sol[sp.Derivative(phi, s)], t),
                        sp.Derivative(cc, s, t): sp.diff(sol[sp.Derivative(cc, s)], t),
                        sp.Derivative(cc, t, s): sp.diff(sol[sp.Derivative(cc, s)], t),
                        sp.Derivative(phi, s, t, t): sp.diff(sol[sp.Derivative(phi, s)], t, 2),
                        sp.Derivative(cc, s, t, t): sp.diff(sol[sp.Derivative(cc, s)], t, 2)})
            e = e.subs(sol)
        return sp.simplify(e)

    r8a, r8b = reduce(e8a), reduce(e8b)
    print(f"RW potential form -> (8): residual of (8a) = {r8a}, of (8b) = {r8b}")
    ok = id1 == 0 and id2 == 0 and idL1 == 0 and idL2 == 0 and r8a == 0 and r8b == 0
    print("identities hold" if ok else "an identity FAILS")
    if mut:
        return 0 if not ok else 1
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main(sys.argv))
