#!/usr/bin/env python3
"""Write a Krawczyk instance as a Lean file of exact rationals for DSS/Krawczyk.lean (#1077).

    python3 export_krawczyk.py capd ENCLOSURES.json NAME OUT.lean [--widen=F]
    python3 export_krawczyk.py arb validated_int_krawczyk_1e-9.json NAME OUT.lean [--widen=F]

capd: the CAPD re-check's file (proof/A_certify.md §10): every interval is [lo, hi] with lo, hi exact doubles in C99
hex, so each end is an exact rational. The centre is the decimal x̂ of the file, exactly; its enclosure in the file
contains it, so F(x̂) lies in F_at_xhat. The half-width is 10^-9 when the file's h is the double nearest 1e-9 (which
is larger), so the Lean box lies inside the integrated one. Y is the float64 inverse of the midpoint of DF, exact as
binary floats; any matrix is allowed. --widen=F multiplies the half-width of DF[0][0] by F: the control that must
make the check fail.
"""
import hashlib
import json
import sys
from fractions import Fraction

import numpy as np


def hexq(s):
    return Fraction(float.fromhex(s))


def lean_q(q):
    q = Fraction(q)
    return f"(({q.numerator} : ℤ) : ℚ) / {q.denominator}"


def lean_I(lo, hi):
    assert lo <= hi
    return f"⟨{lean_q(lo)}, {lean_q(hi)}⟩"


def capd(path, name, out, widen):
    raw = open(path, "rb").read()
    d = json.loads(raw)
    xhat = [Fraction(x) for x in d["xhat"]]
    for i in range(2):
        lo, hi = (hexq(t) for t in d["xhat_enclosure"][i])
        assert lo <= xhat[i] <= hi, "the decimal centre is not inside the file's enclosure"
    hfile = hexq(d["h"])
    h = Fraction(1, 10**9)
    assert h <= hfile, "the Lean half-width must not exceed the integrated one"
    F = [[hexq(t) for t in d["F_at_xhat"][i]] for i in range(2)]
    DF = [[[hexq(t) for t in d["DF_over_X"][i][j]] for j in range(2)] for i in range(2)]
    if widen != 1:
        lo, hi = DF[0][0]
        mid, rad = (lo + hi) / 2, (hi - lo) / 2
        DF[0][0] = [mid - widen * rad, mid + widen * rad]
    mid = np.array([[float((DF[i][j][0] + DF[i][j][1]) / 2) for j in range(2)] for i in range(2)])
    Y = np.linalg.inv(mid)
    Yq = [[Fraction(float(Y[i][j])) for j in range(2)] for i in range(2)]
    sha = hashlib.sha256(raw).hexdigest()
    write(name, out, path, sha, widen, d["producer"], xhat, h, F, DF, Yq)


def write(name, out, path, sha, widen, producer, xhat, h, F, DF, Yq):
    L = [f"import DSS.Krawczyk", "",
         f"/-! Generated by `tools/export_krawczyk.py` from `{path.split('choptuik-large-d/')[-1]}`",
         f"    (sha256 {sha}){'' if widen == 1 else f', with DF[0][0] widened {widen}x (a control)'}.",
         f"    Producer: {producer}. -/", "",
         "namespace DSS.Krawczyk", "",
         f"def {name} : Data where",
         f"  xhat := ![{lean_q(xhat[0])}, {lean_q(xhat[1])}]",
         f"  h := {lean_q(h)}",
         f"  g := ![{lean_I(*F[0])}, {lean_I(*F[1])}]",
         f"  J := ![![{lean_I(*DF[0][0])}, {lean_I(*DF[0][1])}],",
         f"         ![{lean_I(*DF[1][0])}, {lean_I(*DF[1][1])}]]",
         f"  Y := ![![{lean_q(Yq[0][0])}, {lean_q(Yq[0][1])}], ![{lean_q(Yq[1][0])}, {lean_q(Yq[1][1])}]]", ""]
    if widen == 1:
        L += [f"theorem {name}_check : {name}.check = true := by decide +kernel", "",
              f"/-- For every C¹ map whose centre value and Jacobian over the box lie in {name}'s enclosures: exactly one",
              "    zero in the box, and the Jacobian is invertible there. -/",
              f"theorem {name}_unique_simple_zero (g : V → V) (Dg : V → M2)",
              f"    (hg : ∀ x ∈ {name}.box,",
              f"      HasFDerivWithinAt g (LinearMap.toContinuousLinearMap (Matrix.toLin' (Dg x))) {name}.box x)",
              f"    (hE : EnclOK {name} g Dg) :",
              f"    (∃! x, x ∈ {name}.box ∧ g x = 0) ∧ ∀ x ∈ {name}.box, g x = 0 → (Dg x).det ≠ 0 :=",
              f"  krawczyk_of_check {name} {name}_check g Dg hg hE", ""]
    else:
        L += [f"theorem {name}_check_fails : {name}.check = false := by decide +kernel", ""]
    L += ["end DSS.Krawczyk", ""]
    open(out, "w").write("\n".join(L))


def arbq(x):
    """the exact rational ends of an arb ball: midpoint and radius are dyadic"""
    m, e = x.mid().man_exp()
    rm, re = x.rad().man_exp()
    mid = Fraction(int(m)) * Fraction(2) ** int(e)
    rad = Fraction(int(rm)) * Fraction(2) ** int(re)
    return mid - rad, mid + rad


def arbrun(path, name, out, widen):
    """arb: validated_int.py's saved point and box runs through its own krawczyk_assemble (320 bits): g(x^) and J(X)
    as arb balls. The box run covers x^ +- arb(h) with h the file's decimal string, so the Lean half-width h (the same
    decimal, exactly) lies inside it, and x^'s ball contains the decimal centre."""
    import os
    here = os.path.dirname(os.path.abspath(path))
    sys.path.insert(0, here)
    import validated_int as VI
    raw = open(path, "rb").read()
    d = json.loads(raw)
    ok, K, margins, g_hat, JX, JD, dJD = VI.krawczyk_assemble(d["A"], d["wf"], d["h"], d["xi1"], d["point"], d["box"])
    xhat = [Fraction(d["A"]), Fraction(d["wf"])]
    h = Fraction(d["h"])
    F = [list(arbq(g_hat[i])) for i in range(2)]
    DF = [[list(arbq(JX[i][j])) for j in range(2)] for i in range(2)]
    if widen != 1:
        lo, hi = DF[0][0]
        m_, r_ = (lo + hi) / 2, (hi - lo) / 2
        DF[0][0] = [m_ - widen * r_, m_ + widen * r_]
    mid = np.array([[float((DF[i][j][0] + DF[i][j][1]) / 2) for j in range(2)] for i in range(2)])
    Y = np.linalg.inv(mid)
    Yq = [[Fraction(float(Y[i][j])) for j in range(2)] for i in range(2)]
    sha = hashlib.sha256(raw).hexdigest()
    prod = f"validated_int.py krawczyk_assemble on the saved runs (arb; its own test: ok={ok}, margins {margins})"
    write(name, out, path, sha, widen, prod, xhat, h, F, DF, Yq)


def certM(path, name, out, widen):
    """certify_M.py's test of record (proof/A_M.md: `certify_M.py krawczyk --box=...`) from the saved box run, in the
    chart's coordinates (centre 0, half-widths h, h, w_3, w_3, ...): its Y g(p^) and Y Dgt(X) are taken as returned,
    and Y is recomputed by the same lines as krawczyk_test (asserted equal through Y g). The Lean half-widths are the
    run's decimal strings, exactly; the run's arb half-widths contain them."""
    import os
    here = os.path.dirname(os.path.abspath(path))
    sys.path.insert(0, os.path.dirname(here))
    import certify_M as CM
    from flint import arb, arb_mat, ctx
    raw = open(path, "rb").read()
    bx = json.loads(raw)
    res = CM.krawczyk_test(bx, verbose=False)
    M = bx["M"]
    m = M + 1
    ctx.prec = CM.KPREC
    s_ = CM.CS.SysM(M)
    ell = CM.jump_rows(s_, None)
    c, Q, q, varb = CM.CL.load_lohner(bx["sets"])
    Dgt0 = arb_mat(CM.apply_var(ell, varb))
    Dmid = arb_mat([[arb(Dgt0[i, j].mid()) for j in range(m)] for i in range(m)])
    Yb = Dmid.inv()
    Y = arb_mat([[arb(Yb[i, j].mid()) for j in range(m)] for i in range(m)])
    Yg2 = CM.apply_set(Y * ell, c, Q, q)
    assert all(Yg2[i].equal(res["Yg"][i]) if hasattr(Yg2[i], "equal") else str(Yg2[i]) == str(res["Yg"][i])
               for i in range(m)), "Y recomputed does not reproduce krawczyk_test's Y g"
    ws = [Fraction(bx["h"]), Fraction(bx["h"])] + [Fraction(bx["w"][(i // 2) % len(bx["w"])]) for i in range(M - 1)]
    Yq = [[arbq(Y[i, j])[0] for j in range(m)] for i in range(m)]
    assert all(arbq(Y[i, j])[0] == arbq(Y[i, j])[1] for i in range(m) for j in range(m)), "Y must be exact"
    Yg = [list(arbq(res["Yg"][i])) for i in range(m)]
    YJ = [[list(arbq(res["YJ"][i][j])) for j in range(m)] for i in range(m)]
    if widen != 1:
        lo, hi = YJ[0][0]
        m_, r_ = (lo + hi) / 2, (hi - lo) / 2
        YJ[0][0] = [m_ - widen * r_, m_ + widen * r_]
    sha = hashlib.sha256(raw).hexdigest()
    vec = lambda xs: "![" + ", ".join(xs) + "]"
    L = ["import DSS.KrawczykN", "",
         f"/-! Generated by `tools/export_krawczyk.py certM` from `{path.split('choptuik-large-d/')[-1]}`",
         f"    (sha256 {sha}){'' if widen == 1 else f', with YJ[0][0] widened {widen}x (a control)'}.",
         f"    Producer: certify_M.py krawczyk_test (arb, KPREC {CM.KPREC}; its own test: ok={res['ok']}, relative margins",
         f"    {[round(r, 3) for r in res['rel_margins']]}). Coordinates: the chart around p^ (A_M.md §2), centre 0. -/", "",
         "namespace DSS.Krawczyk", "",
         f"def {name} : BoxData {m} where",
         f"  xhat := {vec(['0'] * m)}",
         f"  w := {vec([lean_q(x) for x in ws])}",
         f"  Yg := {vec([lean_I(*Yg[i]) for i in range(m)])}",
         "  YJ := " + vec([vec([lean_I(*YJ[i][j]) for j in range(m)]) for i in range(m)]),
         "  Y := " + vec([vec([lean_q(Yq[i][j]) for j in range(m)]) for i in range(m)]), ""]
    if widen == 1:
        L += [f"theorem {name}_check : {name}.check = true := by decide +kernel", "",
              f"/-- For every C¹ map on the chart box whose Y g(0) and Y Dg over the box lie in {name}'s enclosures:",
              "    exactly one zero in the box, and the Jacobian is invertible there. -/",
              f"theorem {name}_unique_simple_zero (g : Vn {m} → Vn {m}) (Dg : Vn {m} → Mn {m})",
              f"    (hg : ∀ x ∈ {name}.box,",
              f"      HasFDerivWithinAt g (LinearMap.toContinuousLinearMap (Matrix.toLin' (Dg x))) {name}.box x)",
              f"    (hE : {name}.EnclOK g Dg) :",
              f"    (∃! x, x ∈ {name}.box ∧ g x = 0) ∧ ∀ x ∈ {name}.box, g x = 0 → (Dg x).det ≠ 0 :=",
              f"  krawczyk_box {name} {name}_check g Dg hg hE", ""]
    else:
        L += [f"theorem {name}_check_fails : {name}.check = false := by decide +kernel", ""]
    L += ["end DSS.Krawczyk", ""]
    open(out, "w").write("\n".join(L))


if __name__ == "__main__":
    a = [x for x in sys.argv[1:] if not x.startswith("--")]
    o = dict(x[2:].split("=", 1) for x in sys.argv[1:] if x.startswith("--") and "=" in x)
    if a and a[0] == "capd":
        capd(a[1], a[2], a[3], Fraction(o.get("widen", "1")))
    elif a and a[0] == "certM":
        certM(a[1], a[2], a[3], Fraction(o.get("widen", "1")))
    elif a and a[0] == "arb":
        arbrun(a[1], a[2], a[3], Fraction(o.get("widen", "1")))
    else:
        print(__doc__)
        sys.exit(2)
