#!/usr/bin/env python3
"""Write a Krawczyk instance as a Lean file of exact rationals for DSS/Krawczyk.lean (#1077).

    python3 export_krawczyk.py capd ENCLOSURES.json NAME OUT.lean [--widen=F]

capd: the CAPD re-check's file (proof/A_certify.md §10): every interval is [lo, hi] with lo, hi exact doubles in C99
hex, so each end is an exact rational. The centre is the decimal x̂ of the file, exactly; its enclosure in the file
contains it, so F(x̂) lies in F_at_xhat. The half-width is 10^-9 when the file's h is the double nearest 1e-9 (which
is larger), so the Lean box lies inside the integrated one. Y is the float64 inverse of the midpoint of DF, exact as
binary floats; any matrix is allowed. --widen=F multiplies the half-width of DF[0][0] by F: the control that must
make the check fail.
"""
import hashlib
import json
import sys
from fractions import Fraction

import numpy as np


def hexq(s):
    return Fraction(float.fromhex(s))


def lean_q(q):
    q = Fraction(q)
    return f"(({q.numerator} : ℤ) : ℚ) / {q.denominator}"


def lean_I(lo, hi):
    assert lo <= hi
    return f"⟨{lean_q(lo)}, {lean_q(hi)}⟩"


def capd(path, name, out, widen):
    raw = open(path, "rb").read()
    d = json.loads(raw)
    xhat = [Fraction(x) for x in d["xhat"]]
    for i in range(2):
        lo, hi = (hexq(t) for t in d["xhat_enclosure"][i])
        assert lo <= xhat[i] <= hi, "the decimal centre is not inside the file's enclosure"
    hfile = hexq(d["h"])
    h = Fraction(1, 10**9)
    assert h <= hfile, "the Lean half-width must not exceed the integrated one"
    F = [[hexq(t) for t in d["F_at_xhat"][i]] for i in range(2)]
    DF = [[[hexq(t) for t in d["DF_over_X"][i][j]] for j in range(2)] for i in range(2)]
    if widen != 1:
        lo, hi = DF[0][0]
        mid, rad = (lo + hi) / 2, (hi - lo) / 2
        DF[0][0] = [mid - widen * rad, mid + widen * rad]
    mid = np.array([[float((DF[i][j][0] + DF[i][j][1]) / 2) for j in range(2)] for i in range(2)])
    Y = np.linalg.inv(mid)
    Yq = [[Fraction(float(Y[i][j])) for j in range(2)] for i in range(2)]
    sha = hashlib.sha256(raw).hexdigest()
    L = [f"import DSS.Krawczyk", "",
         f"/-! Generated by `tools/export_krawczyk.py capd` from `{path.split('choptuik-large-d/')[-1]}`",
         f"    (sha256 {sha}){'' if widen == 1 else f', with DF[0][0] widened {widen}x (a control)'}.",
         f"    Producer: {d['producer']}. -/", "",
         "namespace DSS.Krawczyk", "",
         f"def {name} : Data where",
         f"  xhat := ![{lean_q(xhat[0])}, {lean_q(xhat[1])}]",
         f"  h := {lean_q(h)}",
         f"  g := ![{lean_I(*F[0])}, {lean_I(*F[1])}]",
         f"  J := ![![{lean_I(*DF[0][0])}, {lean_I(*DF[0][1])}],",
         f"         ![{lean_I(*DF[1][0])}, {lean_I(*DF[1][1])}]]",
         f"  Y := ![![{lean_q(Yq[0][0])}, {lean_q(Yq[0][1])}], ![{lean_q(Yq[1][0])}, {lean_q(Yq[1][1])}]]", ""]
    if widen == 1:
        L += [f"theorem {name}_check : {name}.check = true := by decide +kernel", "",
              f"/-- For every C¹ map whose centre value and Jacobian over the box lie in {name}'s enclosures: exactly one",
              "    zero in the box, and the Jacobian is invertible there. -/",
              f"theorem {name}_unique_simple_zero (g : V → V) (Dg : V → M2)",
              f"    (hg : ∀ x ∈ {name}.box,",
              f"      HasFDerivWithinAt g (LinearMap.toContinuousLinearMap (Matrix.toLin' (Dg x))) {name}.box x)",
              f"    (hE : EnclOK {name} g Dg) :",
              f"    (∃! x, x ∈ {name}.box ∧ g x = 0) ∧ ∀ x ∈ {name}.box, g x = 0 → (Dg x).det ≠ 0 :=",
              f"  krawczyk_of_check {name} {name}_check g Dg hg hE", ""]
    else:
        L += [f"theorem {name}_check_fails : {name}.check = false := by decide +kernel", ""]
    L += ["end DSS.Krawczyk", ""]
    open(out, "w").write("\n".join(L))


if __name__ == "__main__":
    a = [x for x in sys.argv[1:] if not x.startswith("--")]
    o = dict(x[2:].split("=", 1) for x in sys.argv[1:] if x.startswith("--") and "=" in x)
    if a and a[0] == "capd":
        capd(a[1], a[2], a[3], Fraction(o.get("widen", "1")))
    else:
        print(__doc__)
        sys.exit(2)
